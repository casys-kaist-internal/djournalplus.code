#!/usr/bin/env python3
"""Merge the run_main.sh results kept for the paper into one CSV and tables.

Reads <paper_dir>/runs/<db>/<ts>/summary.csv (written by parse_main.py),
maps (fs, fpw) to the paper's configuration names, and writes
<paper_dir>/summary.csv, <paper_dir>/tables.md and <paper_dir>/tps.csv (the
plotting format: workload, database, filesystem, full_page_write, clients,
tps; one row per run). Replacing a run means swapping its directory under
runs/ and running this script again. run_main.sh variants (ext4-uniform,
zfs-16k-fullfill, ...) are left out, unless --variant names the one to
tabulate (its suffix is dropped from the FS names).

Usage: paper_tables.py <paper_dir> [--variant NAME] [workload ...]
       (default: all four workloads)
"""
import csv
import statistics
import sys
from collections import defaultdict
from pathlib import Path

WORKLOADS = ["oltp_write_only", "oltp_update_index", "oltp_update_non_index",
             "oltp_insert"]
CONFIGS = ["EXT4_Raw", "EXT4_App", "XFS_Raw", "XFS_App", "EXT4_Data", "ZFS"]
THREADS = [1, 8, 16, 32, 64]
VARIANTS = tuple(f"-{v}" for v in
                 ["uniform", "fullfill", "odirect", "spin", "nologwriter", "binlog"])
DBS = [("mysql", "MySQL"), ("postgres", "PostgreSQL")]
# (summary column, label, scale) -> label per transaction
MECH_COLS = [("dev_write_mb", "dev KB", 1024), ("wal_mb", "WAL KB", 1024),
             ("wal_fpi", "FPI", 1), ("redo_mb", "redo KB", 1024),
             ("dblwr_mb", "DWB KB", 1024)]


def config(fs, fpw):
    if fs in ("ext4", "xfs"):
        return f"{fs.upper()}_{'App' if fpw == 'on' else 'Raw'}"
    if fs.startswith("ext4-dj"):
        return "EXT4_Data"
    if fs.startswith("zfs"):
        return "ZFS"
    return None


def plot_fs(fs):
    """File system name in tps.csv: ext4, xfs, ext4-dj or zfs."""
    for prefix in ("ext4-dj", "zfs"):
        if fs.startswith(prefix):
            return prefix
    return fs


def main():
    args = sys.argv[1:]
    pdir = Path(args.pop(0))
    variant = None
    if args[:1] == ["--variant"]:
        variant = f"-{args[1]}"
        args = args[2:]
    workloads = args or WORKLOADS
    rows = []
    for f in sorted(pdir.glob("runs/*/*/summary.csv")):
        for r in csv.DictReader(f.open()):
            if variant:
                if not r["fs"].endswith(variant):
                    continue
                r["fs"] = r["fs"].removesuffix(variant)
            elif r["fs"].endswith(VARIANTS):
                continue
            cfg = config(r["fs"], r["fpw"])
            if cfg is None or r["workload"] not in workloads:
                continue
            rows.append({"config": cfg, "source": f.parent.name, **r})
    with (pdir / "summary.csv").open("w", newline="") as out:
        w = csv.DictWriter(out, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    # For plotting: one row per run (the 64-client point has one row per run),
    # full_page_write = PG full_page_writes / MySQL innodb_doublewrite
    order = {k: i for i, k in enumerate(
        ["postgres", "mysql", "ext4", "xfs", "ext4-dj", "zfs", "off", "on"])}
    plot = sorted(rows, key=lambda r: (
        r["workload"], order.get(r["db"], 9), order.get(plot_fs(r["fs"]), 9),
        order.get(r["fpw"], 9), int(r["threads"]), int(r["run"])))
    with (pdir / "tps.csv").open("w", newline="") as out:
        w = csv.writer(out)
        w.writerow(["workload", "database", "filesystem", "full_page_write",
                    "clients", "tps"])
        for r in plot:
            w.writerow([r["workload"], r["db"], plot_fs(r["fs"]), r["fpw"],
                        r["threads"], r["tps"]])

    tps = defaultdict(list)    # (db, workload, config, threads) -> [tps]
    kb = defaultdict(list)     # device write KB per transaction
    mech = defaultdict(lambda: defaultdict(list))  # per-mechanism counters
    for r in rows:
        key = (r["db"], r["workload"], r["config"], int(r["threads"]))
        trx = int(r["transactions"])
        tps[key].append(float(r["tps"]))
        if r["dev_write_kb_per_trx"]:
            kb[key].append(float(r["dev_write_kb_per_trx"]))
        for col, name, scale in MECH_COLS:
            if r[col]:
                mech[key][name].append(float(r[col]) * scale / trx)
        for col in ("cpu_util_pct", "cpu_iowait_pct", "avg_ms", "p99_ms"):
            if r[col]:
                mech[key][col].append(float(r[col]))

    def cell(vals, ref=None):
        if not vals:
            return "–"
        m = statistics.mean(vals)
        s = f"{m:,.0f}"
        if len(vals) > 1:
            s += f" ±{statistics.stdev(vals) / m * 100:.0f}%"
        return s

    md = [f"# Sysbench special — baselines ({', '.join(workloads)})"
          f"{f' — variant {variant[1:]}' if variant else ''}\n",
          "Generated by `bench/scripts/sysbench/paper_tables.py`. TPS; the 64-thread",
          "point is the mean of 3 runs ± relative stdev.\n"]
    for db, name in DBS:
        md.append(f"## {name}\n")
        for wl in workloads:
            md.append(f"### {wl}\n")
            md.append("| config | " + " | ".join(map(str, THREADS)) + " |")
            md.append("|---|" + "---|" * len(THREADS))
            for c in CONFIGS:
                md.append(f"| {c} | " + " | ".join(
                    cell(tps[(db, wl, c, t)]) for t in THREADS) + " |")
            md.append("")
        md.append(f"### {name}: ratio to EXT4_App / XFS_App (64 threads, mean)\n")
        md.append("| workload | EXT4 Raw/App | XFS Raw/App | EXT4_Data/EXT4_App"
                  " | ZFS/EXT4_App |")
        md.append("|---|---|---|---|---|")
        for wl in workloads:
            m = {c: statistics.mean(tps[(db, wl, c, 64)]) for c in CONFIGS
                 if tps[(db, wl, c, 64)]}

            def ratio(a, b):
                return f"{m[a] / m[b]:.2f}" if a in m and b in m else "–"
            md.append(f"| {wl} | {ratio('EXT4_Raw', 'EXT4_App')} | "
                      f"{ratio('XFS_Raw', 'XFS_App')} | "
                      f"{ratio('EXT4_Data', 'EXT4_App')} | "
                      f"{ratio('ZFS', 'EXT4_App')} |")
        md.append("")
        md.append(f"### {name}: device write KB per transaction (64 threads, mean)\n")
        md.append("| workload | " + " | ".join(CONFIGS) + " |")
        md.append("|---|" + "---|" * len(CONFIGS))
        for wl in workloads:
            md.append(f"| {wl} | " + " | ".join(
                f"{statistics.mean(kb[(db, wl, c, 64)]):.1f}"
                if kb[(db, wl, c, 64)] else "–" for c in CONFIGS) + " |")
        md.append("")
        cols = ["dev KB", "WAL KB", "FPI", "redo KB", "DWB KB", "cpu_util_pct",
                "cpu_iowait_pct", "avg_ms", "p99_ms"]
        for wl in workloads:
            md.append(f"### {name}: {wl} counters per transaction"
                      " (64 threads, mean)\n")
            md.append("| config | " + " | ".join(cols) + " |")
            md.append("|---|" + "---|" * len(cols))
            for c in CONFIGS:
                m = mech[(db, wl, c, 64)]
                md.append(f"| {c} | " + " | ".join(
                    f"{statistics.mean(m[k]):.2f}" if m.get(k) else "–"
                    for k in cols) + " |")
            md.append("")
    (pdir / "tables.md").write_text("\n".join(md))
    print(f"wrote {len(rows)} rows, {pdir / 'tables.md'}")


if __name__ == "__main__":
    main()
