#!/usr/bin/env python3
"""TPC-C (BenchBase) evaluation tables from <dir>/runs/<db>/<ts>/ (run_tpcc.sh
result directories, copied into the paper's evaluation directory).

Writes <dir>/tpcc.csv, one row per measurement: database, file system,
full_page_write (PG full_page_writes / MySQL innodb_doublewrite), configuration
name, terminals, run, throughput, tpmC (new orders counted by the database over
the run, and BenchBase's completed NewOrders), latency, the device and
WAL/redo writes per new order, full-page images or doublewrite pages per new
order, BenchBase's CPU and the host's; and <dir>/tables.md: per database the
tpmC by terminal count and configuration (repeated points: mean, with the
range), and Raw ÷ App per file system. A later run of the same configuration
replaces an earlier one.
Usage: paper_tpcc.py <dir>
"""
import csv
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pilot_report  # noqa: E402

LABEL = re.compile(r"(mysql|postgres)_tpcc_(.+?)_fpw_(on|off)_w(\d+)_c(\d+)_r(\d+)$")
ORDER = ["EXT4_Raw", "EXT4_App", "XFS_Raw", "XFS_App", "EXT4_Data", "ZFS", "BTRFS"]


def config(fs, fpw):
    base = {"ext4": "EXT4", "xfs": "XFS"}.get(fs)
    if base:
        return f"{base}_{'App' if fpw == 'on' else 'Raw'}"
    if fs.startswith("ext4-dj"):
        return "EXT4_Data"
    if fs.startswith("zfs"):
        return "ZFS"
    if fs == "btrfs":
        return "BTRFS"
    return fs


def num(x):
    try:
        return float(str(x).split()[0].rstrip("%"))
    except (ValueError, IndexError):
        return None


def main():
    top = Path(sys.argv[1])
    rows = {}
    for run in sorted(top.glob("runs/*/*/")):
        for xml in sorted(run.glob("*_r[0-9]*.xml")):
            name = xml.stem
            m = LABEL.match(name)
            if not m or not list(run.glob(f"{name}/*.summary.json")):
                continue
            db, fs, fpw, wh, terminals, rep = m.groups()
            r = pilot_report.run_row(str(run), name)
            lat = [float(x) for x in r["latency avg / p95 / p99 (ms)"].split(" / ")]
            row = {
                "database": db, "filesystem": fs, "full_page_write": fpw,
                "config": config(fs, fpw), "warehouses": int(wh), "terminals": int(terminals),
                "run": int(rep), "source": run.name,
                "txn_per_s": r["throughput (txn/s)"],
                "tpmC_database": r["tpmC, database (new orders over the whole run)"],
                "tpmC_benchbase": r["tpmC, BenchBase (completed NewOrder, measured)"],
                "latency_avg_ms": lat[0], "latency_p95_ms": lat[1], "latency_p99_ms": lat[2],
                "device_kb_per_new_order": num(r.get("device writes per new order (KB)")),
                "log_kb_per_new_order": num(r.get("WAL per new order (KB)", r.get("redo per new order (KB)"))),
                "fpi_or_doublewrite_pages_per_new_order": num(
                    r.get("full-page images per new order", r.get("doublewrite pages per new order (batches only)"))),
                "benchbase_cores": num(r["BenchBase JVM CPU (cores)"]),
                "host_busy_pct": num(r["host CPU busy (mpstat)"]),
            }
            rows[(db, fs, fpw, int(terminals), int(rep))] = row   # later sources replace
    rows = [rows[k] for k in sorted(rows)]
    if not rows:
        sys.exit("no runs")
    with (top / "tpcc.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    md = ["# TPC-C (BenchBase): tables\n",
          "Generated by `scripts/paper_tpcc.py`. tpmC = new orders per minute counted by the",
          "database over each 5-min measurement; repeated points: mean (range).\n"]
    for db in ("postgres", "mysql"):
        sel = [r for r in rows if r["database"] == db]
        if not sel:
            continue
        cfgs = [c for c in ORDER if any(r["config"] == c for r in sel)]
        cfgs += sorted({r["config"] for r in sel} - set(cfgs))
        terms = sorted({r["terminals"] for r in sel})
        val = defaultdict(list)
        for r in sel:
            val[(r["config"], r["terminals"])].append(r["tpmC_database"])

        def cell(c, t):
            v = val.get((c, t))
            if not v:
                return ""
            if len(v) == 1:
                return f"{v[0]:,}"
            return f"{statistics.mean(v):,.0f} ({min(v):,}–{max(v):,})"

        md.append(f"## {'PostgreSQL' if db == 'postgres' else 'MySQL'}: tpmC\n")
        md.append("| terminals | " + " | ".join(cfgs) + " |")
        md.append("|---" * (len(cfgs) + 1) + "|")
        for t in terms:
            md.append(f"| {t} | " + " | ".join(cell(c, t) for c in cfgs) + " |")
        pairs = [(b, f"{b}_Raw", f"{b}_App") for b in ("EXT4", "XFS")
                 if f"{b}_Raw" in cfgs and f"{b}_App" in cfgs]
        if pairs:
            md.append("\nRaw ÷ App:\n")
            md.append("| terminals | " + " | ".join(p[0] for p in pairs) + " |")
            md.append("|---" * (len(pairs) + 1) + "|")
            for t in terms:
                cells = []
                for _, raw, app in pairs:
                    a, b = val.get((raw, t)), val.get((app, t))
                    cells.append(f"{statistics.mean(a) / statistics.mean(b):.2f}" if a and b else "")
                md.append(f"| {t} | " + " | ".join(cells) + " |")
        if "EXT4_App" in cfgs:
            md.append("\n÷ EXT4_App:\n")
            others = [c for c in cfgs if c != "EXT4_App"]
            md.append("| terminals | " + " | ".join(others) + " |")
            md.append("|---" * (len(others) + 1) + "|")
            for t in terms:
                b = val.get(("EXT4_App", t))
                cells = [f"{statistics.mean(val[(c, t)]) / statistics.mean(b):.2f}"
                         if b and val.get((c, t)) else "" for c in others]
                md.append(f"| {t} | " + " | ".join(cells) + " |")
        last = max(terms)
        md.append(f"\nAt {last} terminals (mean of the runs):\n")
        md.append("| config | txn/s | latency avg / p95 / p99 (ms) | device KB per new order "
                  "| WAL/redo KB per new order | FPI / doublewrite pages (batches only) per new order "
                  "| BenchBase cores | host busy |")
        md.append("|---" * 8 + "|")
        for c in cfgs:
            rs = [r for r in sel if r["config"] == c and r["terminals"] == last]
            if not rs:
                continue

            def mean(k):
                v = [r[k] for r in rs if r[k] is not None]
                return statistics.mean(v) if v else float("nan")
            md.append(f"| {c} | {mean('txn_per_s'):,.0f} | {mean('latency_avg_ms'):.2f} / "
                      f"{mean('latency_p95_ms'):.2f} / {mean('latency_p99_ms'):.2f} "
                      f"| {mean('device_kb_per_new_order'):.0f} | {mean('log_kb_per_new_order'):.1f} "
                      f"| {mean('fpi_or_doublewrite_pages_per_new_order'):.2f} "
                      f"| {mean('benchbase_cores'):.1f} | {mean('host_busy_pct'):.0f}% |")
        md.append("")
    (top / "tables.md").write_text("\n".join(md))
    print(f"{len(rows)} measurements -> {top / 'tpcc.csv'}, {top / 'tables.md'}")


if __name__ == "__main__":
    main()
